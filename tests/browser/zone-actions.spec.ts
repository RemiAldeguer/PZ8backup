import { test, expect } from '@playwright/test';
import type { AppData, Project, Zone } from '../../shared/types';
import { loginTestAdmin } from '../auth-fixture';

test('zones : édition, confirmation explicite, projet ajouté entre-temps et suppression en cascade', async ({ page, request }) => {
  await loginTestAdmin(page.request); await loginTestAdmin(request);
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  const before = await (await request.get('/api/state')).json() as AppData;
  const existingZone = before.zones.find(zone => before.projects.some(project => project.zoneId === zone.id))!;
  await page.goto('/#zones/' + existingZone.id + '/projects');
  const nav = page.getByRole('navigation', { name: 'Vues de la zone', exact: true });
  await nav.getByRole('button', { name: 'Actions de la zone ' + existingZone.name, exact: true }).click();
  await page.getByRole('menuitem', { name: 'Supprimer la zone', exact: true }).click();
  const deletion = page.getByRole('dialog', { name: 'Supprimer la zone', exact: true });
  await expect(deletion.getByRole('button', { name: 'Supprimer la zone et ses projets', exact: true })).toBeDisabled();
  await expect(deletion.getByRole('alert')).toContainText('cette action est définitive');
  for (const project of before.projects.filter(item => item.zoneId === existingZone.id)) await expect(deletion.getByRole('list', { name: 'Projets qui seront supprimés', exact: true })).toContainText(project.name);
  await deletion.getByRole('button', { name: 'Annuler', exact: true }).click();

  await page.getByRole('button', { name: 'Créer une zone', exact: true }).click();
  const creation = page.getByRole('dialog', { name: 'Nouvelle zone', exact: true });
  await creation.getByLabel('Nom de la zone', { exact: true }).fill('Recette gestion zones');
  await creation.getByRole('button', { name: 'Créer la zone', exact: true }).click();
  await expect(creation).not.toBeVisible();
  const created = (await (await request.get('/api/state')).json() as AppData).zones.find(zone => zone.name === 'Recette gestion zones') as Zone;
  const sidebar = page.getByRole('complementary', { name: 'Navigation principale', exact: true });
  await sidebar.getByRole('button', { name: 'Actions de la zone ' + created.name, exact: true }).click();
  await page.getByRole('menuitem', { name: 'Modifier la zone', exact: true }).click();
  const edit = page.getByRole('dialog', { name: 'Modifier la zone', exact: true });
  await expect(edit.getByLabel('Nom de la zone', { exact: true })).toHaveValue(created.name);
  await edit.getByLabel('Nom de la zone', { exact: true }).fill('Zone renommée');
  await edit.getByLabel('Couleur', { exact: true }).fill('#bb55dd');
  await edit.getByRole('button', { name: 'Enregistrer', exact: true }).click();
  await expect(edit).not.toBeVisible();
  await page.goto('/#zones/' + created.id + '/list');
  await nav.getByRole('button', { name: 'Actions de la zone Zone renommée', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Supprimer la zone', exact: true }).click();
  await expect(deletion.getByRole('button', { name: 'Supprimer la zone', exact: true })).toBeDisabled();
  await deletion.getByRole('checkbox').check();
  await expect(deletion.getByRole('button', { name: 'Supprimer la zone', exact: true })).toBeEnabled();
  const added = await request.post('/api/projects', { data: { name: 'Projet concurrent', zoneId: created.id } });
  expect(added.status()).toBe(201); const project = await added.json() as Project;
  await deletion.getByRole('button', { name: 'Supprimer la zone', exact: true }).click();
  await expect(deletion.getByText('Les projets de cette zone ont changé.', { exact: false })).toBeVisible();
  expect((await (await request.get('/api/state')).json() as AppData).zones.find(zone => zone.id === created.id)).toEqual({ ...created, name: 'Zone renommée', color: '#bb55dd' });
  await deletion.getByRole('button', { name: 'Annuler', exact: true }).click();
  const taskResponse = await request.post('/api/tasks', { data: { projectId: project.id, title: 'Tâche à supprimer avec sa zone' } });
  expect(taskResponse.status()).toBe(201); const task = await taskResponse.json() as { id: string };
  expect((await request.post('/api/time-entries', { data: { taskId: task.id, resourceId: before.resources[0].id, date: before.today, hours: 1, validated: true } })).status()).toBe(201);
  await page.reload();
  await nav.getByRole('button', { name: 'Actions de la zone Zone renommée', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Supprimer la zone', exact: true }).click();
  await expect(deletion.getByRole('list', { name: 'Projets qui seront supprimés', exact: true })).toContainText(project.name);
  await expect(deletion.getByRole('button', { name: 'Supprimer la zone et ses projets', exact: true })).toBeDisabled();
  await deletion.getByRole('checkbox').check();
  await deletion.getByRole('button', { name: 'Supprimer la zone et ses projets', exact: true }).click();
  await expect(deletion).not.toBeVisible();
  await expect(page).toHaveURL(/#projects$/);
  await page.reload();
  await expect(sidebar.getByRole('button', { name: 'Actions de la zone Zone renommée', exact: true })).toHaveCount(0);
  const after = await (await request.get('/api/state')).json() as AppData;
  expect(after.zones).toEqual(before.zones);
  expect(after.projects).toEqual(before.projects);
  expect(after.tasks).toEqual(before.tasks);
  expect(after.timeEntries).toEqual(before.timeEntries);
  expect(after.resources).toEqual(before.resources);
  expect(errors).toEqual([]);
});
