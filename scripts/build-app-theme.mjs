import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

// Compatibility adapter for the existing views. New UI should use semantic
// theme variables directly. Regenerate after changing an existing stylesheet.
const repository = dirname(dirname(fileURLToPath(import.meta.url)));
const src = join(repository, 'src');
async function styles(directory) {
  const result = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.name === 'theme' || entry.name === 'pz7-access') continue;
    const path = join(directory, entry.name);
    if (entry.isDirectory()) result.push(...await styles(path));
    else if (path.endsWith('.css')) result.push(path);
  }
  return result.sort();
}
function rgb(hex) {
  const raw = hex.slice(1);
  const value = raw.length === 3 || raw.length === 4 ? [...raw].map(char => char + char).join('') : raw;
  return { channels: [0, 2, 4].map(start => parseInt(value.slice(start, start + 2), 16)), alpha: value.length === 8 ? parseInt(value.slice(6), 16) / 255 : 1 };
}
function hsl(channels) {
  const [r, g, b] = channels.map(channel => channel / 255);
  const max = Math.max(r, g, b), min = Math.min(r, g, b), delta = max - min, lightness = (max + min) / 2;
  let hue = 0;
  if (delta) hue = 60 * (max === r ? ((g - b) / delta + (g < b ? 6 : 0)) : max === g ? (b - r) / delta + 2 : (r - g) / delta + 4);
  return { hue, saturation: delta === 0 ? 0 : delta / (1 - Math.abs(2 * lightness - 1)), lightness };
}
function neutral(channels) {
  const { hue, saturation } = hsl(channels);
  return Math.max(...channels) - Math.min(...channels) <= 34 || (hue >= 180 && hue <= 235 && saturation <= .42);
}
function luminance(channels) {
  const [r, g, b] = channels.map(channel => { const value = channel / 255; return value <= .04045 ? value / 12.92 : ((value + .055) / 1.055) ** 2.4; });
  return r * .2126 + g * .7152 + b * .0722;
}
function contrast(a, b) {
  const values = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (values[0] + .05) / (values[1] + .05);
}
function readable(channels, background, lighter) {
  let result = channels;
  for (let step = 0; step <= 100; step++) {
    result = channels.map(channel => Math.round(lighter ? channel + (255 - channel) * step / 100 : channel * (1 - step / 100)));
    if (contrast(result, background) >= 4.7) break;
  }
  return '#' + result.map(channel => channel.toString(16).padStart(2, '0')).join('');
}
function adapt(hex, property, solidBackground) {
  const { channels, alpha } = rgb(hex), shade = hsl(channels);
  const isNeutral = neutral(channels), isText = property === 'color';
  let result;
  if (isText) {
    if (solidBackground) {
      const background = rgb(solidBackground), fill = hsl(background.channels);
      if (!neutral(background.channels) && fill.lightness <= .68 && background.alpha === 1)
        return readable(channels, background.channels, luminance(channels) > luminance(background.channels) && contrast([255, 255, 255], background.channels) >= 4.7);
    }
    if (shade.lightness >= .92) return hex; // White labels on filled controls.
    if (isNeutral) result = shade.lightness <= .35 ? 'var(--ink)' : 'var(--muted)';
    else result = `light-dark(${readable(channels, [233, 238, 245], false)}, ${readable(channels, [39, 55, 77], true)})`;
  } else if (property.includes('border') || property.includes('outline')) {
    if (!isNeutral) return hex;
    result = shade.lightness >= .98 ? 'var(--surface)' : 'var(--border)';
  } else if (property.includes('shadow')) {
    if (!isNeutral) return hex;
    result = 'var(--theme-shadow)';
  } else if (isNeutral && (shade.lightness <= .3 || shade.lightness >= .85 || Math.max(...channels) - Math.min(...channels) <= 34)) {
    result = shade.lightness >= .99 ? 'var(--surface)' : shade.lightness >= .96 ? 'var(--surface-subtle)' : shade.lightness >= .85 ? 'var(--surface-muted)' : shade.lightness <= .3 ? 'var(--surface-strong)' : 'var(--neutral-fill)';
  } else {
    // Keep categorical colours; adapt pastel fills to a legible dark tint.
    if (shade.lightness <= .68) return hex;
    const saturation = Math.round(Math.max(.28, Math.min(.58, shade.saturation)) * 100);
    result = `light-dark(${hex}, hsl(${Math.round(shade.hue)} ${saturation}% 20%))`;
  }
  return alpha === 1 ? result : `color-mix(in srgb, ${result} ${Math.round(alpha * 100)}%, transparent)`;
}
const properties = /^(color|background(?:-color)?|border(?:-(?:top|right|bottom|left))?(?:-color)?|box-shadow|outline(?:-color)?)$/;
const output = postcss.root();
output.append(postcss.comment({text: 'Generated by scripts/build-app-theme.mjs; semantic palette and typography adapter for legacy views.'}));
for (const file of await styles(src)) {
  const input = postcss.parse(await readFile(file, 'utf8'));
  const transformed = input.clone();
  const backgrounds = new WeakMap();
  transformed.walkRules(rule => {
    const solid = rule.nodes.find(node => node.type === 'decl' && /^background(?:-color)?$/.test(node.prop) && /^#[a-f\d]{3,8}$/i.test(node.value));
    if (solid) backgrounds.set(rule, solid.value);
  });
  transformed.walkDecls(declaration => {
    const rule = declaration.parent;
    const selector = rule.type === 'rule' ? rule.selector : '';
    if (!selector || /:root|\.auth-intro|\.sidebar|\.pz-sidebar/.test(selector)) { declaration.remove(); return; }
    const original = declaration.value;
    if (properties.test(declaration.prop)) {
      const localBackground = backgrounds.get(rule);
      declaration.value = original.replace(/#[a-f\d]{3,8}\b/gi, colour => adapt(colour, declaration.prop, localBackground));
      if (declaration.prop.startsWith('background')) declaration.value = declaration.value.replace(/\bwhite\b/gi, 'var(--surface)');
    } else if (declaration.prop === 'font-size' && /^\d+px$/.test(original)) {
      const size = parseInt(original, 10);
      declaration.value = size < 10 ? '10px' : size <= 12 ? `${size + 1}px` : original;
    }
    // Keep an unchanged variant fill too: otherwise an adapted base class
    // would override it simply because this adapter is loaded afterwards.
    if (declaration.value === original && !properties.test(declaration.prop)) declaration.remove();
  });
  transformed.walkComments(comment => comment.remove());
  let removed;
  do {
    removed = false;
    transformed.walk(node => {
      if ((node.type === 'rule' || node.type === 'atrule') && node.nodes?.length === 0) { node.remove(); removed = true; }
    });
  } while (removed);
  if (transformed.nodes.length) {
    output.append(postcss.comment({text: relative(repository, file)}));
    transformed.nodes.forEach(node => output.append(node.clone()));
  }
}
await writeFile(join(src, 'theme', 'legacy-theme.css'), output.toString() + '\n');
console.log(`Theme adapter generated for ${(await styles(src)).length} stylesheets.`);
